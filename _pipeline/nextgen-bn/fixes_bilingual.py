"""英文版譯者回報的中文問題，兩邊一起改（E1-E10）。"""
def patch(fn, pairs, label=""):
    s = open(fn, encoding='utf-8').read(); n = 0
    for a, b in pairs:
        if a not in s:
            print("  MISS[%s] %s" % (fn, a[:60])); continue
        s = s.replace(a, b, 1); n += 1
    open(fn, 'w', encoding='utf-8').write(s)
    print("%s %s: %d/%d" % (fn, label, n, len(pairs)))

